/// Isolate network and synthesis correctness from CPU/GPU analysis phase branch differences.
/// The reference is the decoded NVIDIA Colab FLAC, not output generated by this implementation.
#[test]
fn gpu_speech_spectra_reconstruct_reference_audio() {
    let Ok(path) = std::env::var("HUSH_MODEL") else {
        return;
    };
    let decode = |bytes: &[u8]| {
        assert!(bytes.len().is_multiple_of(4));
        bytes
            .as_chunks::<4>()
            .0
            .iter()
            .map(|b| f32::from_le_bytes(*b))
            .collect::<Vec<_>>()
    };
    let input = decode(include_bytes!("fixtures/colab-t4-speech-stft.f32"));
    let expected = decode(include_bytes!("fixtures/colab-t4-speech-output.f32"));
    let bins = 161;
    let frames = 51;
    assert_eq!(input.len(), frames * bins * 2);
    assert_eq!(expected.len(), 8000);
    let mut model = Streaming::load(path, 3, 0).unwrap();
    let mut magnitudes = vec![vec![0.0; frames]; bins];
    let mut phases = vec![vec![0.0; frames]; bins];
    for (t, frame) in input.chunks_exact(bins * 2).enumerate() {
        let (mut mag, phase) = model.step(&frame[..bins], &frame[bins..]).unwrap();
        // NVIDIA's online script applies the guard only after the first frame.
        if t > 0 && mag.iter().filter(|x| **x <= 0.0).count() * 2 > bins {
            mag.fill(0.0);
        }
        for k in 0..bins {
            magnitudes[k][t] = mag[k].max(0.0).exp_m1();
            phases[k][t] = phase[k];
        }
    }
    let actual = audio::istft(&magnitudes, &phases, 320, 160, 320).unwrap();
    check("waveform", 0, &expected, &actual, 100.0, 2e-6);
}
