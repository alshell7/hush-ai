//! FP32 regressions against NVIDIA's StreamingSEMamba on T4, including fused CUDA kernels.
use hush_core::{audio, Streaming};

#[path = "support/gpu_fixture.rs"]
mod gpu_fixture;

fn check(name: &str, frame: usize, expected: &[f32], actual: &[f32], min_snr: f64, max_error: f32) {
    assert_eq!(expected.len(), actual.len());
    let mut power = 0.0f64;
    let mut error = 0.0f64;
    let mut peak = 0.0f32;
    for (&a, &b) in expected.iter().zip(actual) {
        let delta = if name == "phase" {
            (b - a).sin().atan2((b - a).cos())
        } else {
            b - a
        };
        power += (a as f64).powi(2);
        error += (delta as f64).powi(2);
        peak = peak.max(delta.abs());
    }
    let snr = if error == 0.0 {
        f64::INFINITY
    } else if power == 0.0 {
        f64::NEG_INFINITY
    } else {
        10.0 * (power / error).log10()
    };
    assert!(
        snr >= min_snr && peak < max_error,
        "frame {frame} {name}: SNR {snr:.2} dB, max error {peak}"
    );
}

fn check_short_trace(bytes: &[u8]) {
    let Ok(path) = std::env::var("HUSH_MODEL") else {
        return;
    };
    let expected: Vec<f32> = bytes
        .as_chunks::<4>()
        .0
        .iter()
        .map(|b| f32::from_le_bytes(*b))
        .collect();
    assert_eq!(expected.len(), 8 * 1936);
    let mut model = Streaming::load(path, 3, 0).unwrap();
    for t in 0..8 {
        let mag: Vec<_> = (0..161)
            .map(|f| ((f * 17 + t * 13) % 101) as f32 / 100.0)
            .collect();
        let phase: Vec<_> = (0..161)
            .map(|f| (((f * 23 + t * 31) % 200) as f32 - 100.0) / 100.0)
            .collect();
        let (mag, phase) = model.step(&mag, &phase).unwrap();
        let (conv, ssm) = model.temporal_state(0).unwrap();
        let conv: Vec<_> = conv.iter().step_by(257).copied().collect();
        let ssm: Vec<_> = ssm.iter().step_by(257).copied().collect();
        let mut at = t * 1936;
        for (name, actual, snr, peak) in [
            ("magnitude", mag.as_slice(), 90.0, 1e-5),
            ("phase", phase.as_slice(), 90.0, 1e-3),
            ("conv_state", conv.as_slice(), 110.0, 1e-4),
            ("ssm_state", ssm.as_slice(), 110.0, 1e-4),
        ] {
            check(name, t, &expected[at..at + actual.len()], actual, snr, peak);
            at += actual.len();
        }
        assert_eq!(at, (t + 1) * 1936);
    }
}

