fn check_fused_case(bytes: &[u8]) {
    let Ok(path) = std::env::var("HUSH_MODEL") else {
        return;
    };
    let results = gpu_fixture::compare(&path, bytes).unwrap();
    // Provisional bounds for the expanded profiles. The original short-trace gates above
    // remain unchanged. See docs/ACCURACY.md for measured errors and coverage limits.
    for ((name, min_snr, max_error), actual) in [
        ("magnitude", 90.0, 1e-5),
        ("phase", 82.0, 2e-3),
        ("conv_state", 103.0, 1e-4),
        ("ssm_state", 100.0, 1e-4),
    ]
    .into_iter()
    .zip(results)
    {
        assert!(
            actual.min_snr >= min_snr && actual.max_error < max_error,
            "{name}: SNR {:.2} dB, max error {}",
            actual.min_snr,
            actual.max_error
        );
    }
}

